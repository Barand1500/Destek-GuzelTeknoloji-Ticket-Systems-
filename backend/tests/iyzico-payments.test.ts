const config = { apiKey: 'fixture-api', secretKey: 'fixture-secret', mode: 'sandbox' as const };
const billing = { name: 'Test', surname: 'Customer', identityNumber: '11111111111', email: 'test@example.invalid', phone: '05550000000', address: 'Test billing address', city: 'Istanbul', country: 'Turkey', renewalConsent: true };
test('payment transport signs exact request, restricts redirects and encrypts secrets', () => {
  const auth = iyzicoAuthorization(config, '/payment/auth', '{}', 'nonce');
  const signature = createHmac('sha256', config.secretKey).update('nonce/payment/auth{}').digest('hex');
  assert.equal(Buffer.from(auth.Authorization.slice(8), 'base64').toString(), `apiKey:fixture-api&randomKey:nonce&signature:${signature}`);
  const encrypted = sealPayment(config);
  assert.ok(!encrypted.includes(config.secretKey)); assert.deepEqual(openPayment(encrypted), config);
  assert.throws(() => openPayment(encrypted + 'invalid'));
  assert.equal(new URL(hostedPaymentUrl('https://sandbox-cpp.iyzipay.com?token=fixture', 'sandbox')).hostname, 'sandbox-cpp.iyzipay.com');
  assert.throws(() => hostedPaymentUrl('https://evil.example?token=fixture', 'sandbox'));
  const expected = { attemptId: 'attempt', orderId: 'order', amount: '10.00', currency: 'TRY' };
  const result = { status: 'success', paymentId: 'payment', basketId: 'order', currency: 'TRY', price: 10, paidPrice: 10, installment: 1, fraudStatus: 1, paymentStatus: 'SUCCESS' };
  assert.equal(verifiedIyzicoResult(result, expected)?.outcome, 'PAID');
  assert.equal(verifiedIyzicoResult({ ...result, fraudStatus: 0 }, expected), null);
  for (const patch of [{ currency: 'EUR' }, { price: 11 }, { paidPrice: 12 }, { basketId: 'other' }, { installment: 2 }]) assert.throws(() => verifiedIyzicoResult({ ...result, ...patch }, expected), { code: 'PAYMENT_MISMATCH' });
});

test('hosted checkout and recurring payments preserve single grants, consent and uncertain dispatch claims', async () => {
  const owner = await db.user.create({ data: { name: 'Payment fixture ' + randomUUID(), role: 'CUSTOMER', passwordHash: 'fixture' } });
  const other = await db.user.create({ data: { name: 'Payment fixture other ' + randomUUID(), role: 'CUSTOMER', passwordHash: 'fixture' } });
  const actor = { id: owner.id, name: owner.name, email: '', role: 'CUSTOMER' as const, departmentIds: [], sessionId: '', ipAddress: '127.0.0.1' };
  const admin = { ...actor, role: 'ADMIN' as const };
  const originalFetch = globalThis.fetch, originalTx = db.$transaction, originalGateway = db.paymentGatewaySettings.findUnique;
  const settings = { id: 'default', enabled: true, recurringEnabled: true, testedAt: new Date(), credentialsCiphertext: sealPayment(config), mode: 'sandbox', publicUrl: 'https://payment.example.invalid', fingerprint: 'fixture', lastError: null };
  db.paymentGatewaySettings.findUnique = (async () => settings) as any;
  db.$transaction = ((callback: any, options: any) => typeof callback === 'function' ? originalTx.call(db, (tx: any) => { tx.paymentGatewaySettings.findUnique = async () => settings; return callback(tx); }, options) : originalTx.call(db, callback, options)) as typeof originalTx;
  const results = new Map<string, any>(), requests: { path: string; body: any }[] = [];
  let uncertain = false;
  globalThis.fetch = (async (url: any, init: any) => {
    const path = new URL(String(url)).pathname, body = JSON.parse(init.body);
    requests.push({ path, body });
    let value: any;
    if (path.includes('/initialize/')) {
      assert.equal(body.forceThreeDS, true); assert.deepEqual(body.enabledInstallments, [1]); assert.equal(body.paymentCard, undefined);
      const token = randomUUID();
      results.set(token, { status: 'success', token, paymentId: randomUUID(), basketId: body.basketId, price: body.price, paidPrice: body.paidPrice, currency: body.currency, installment: 1, fraudStatus: 1, paymentStatus: 'SUCCESS', cardUserKey: 'stored-user', cardToken: 'stored-card' });
      value = { status: 'success', token, paymentPageUrl: 'https://sandbox-cpp.iyzipay.com?token=' + token };
    } else if (path.includes('/ecom/detail')) value = results.get(body.token) || { status: 'failure', errorCode: 'NOT_FOUND' };
    else if (path === '/payment/auth') {
      assert.equal(body.installment, 1); assert.deepEqual(body.paymentCard, { cardUserKey: 'stored-user', cardToken: 'stored-card' });
      if (uncertain) throw new Error('simulated network interruption');
      value = { status: 'success', paymentId: randomUUID(), basketId: body.basketId, price: body.price, paidPrice: body.paidPrice, currency: body.currency, installment: 1, fraudStatus: 1, paymentStatus: 'SUCCESS' };
      results.set(body.conversationId, value);
    } else if (path === '/payment/detail') value = results.get(body.paymentConversationId) || { status: 'failure', errorCode: 'NOT_FOUND' };
    else value = { status: 'success' };
    return new Response(JSON.stringify(value), { status: 200 });
  }) as typeof fetch;
  const makeOrder = async (extra: any = {}) => db.creditOrder.create({ data: { customerId: owner.id, requestedById: owner.id, requestKey: randomUUID(), inputHash: 'a'.repeat(64), kind: 'TOP_UP', name: 'Payment fixture', credits: 10, total: '10', currency: 'TRY', validityDays: 30, ...extra } });
  try {
    await assert.rejects(savePaymentSettings(actor, {}), { code: 'FORBIDDEN' });
    const safe = await getPaymentSettings(admin);
    assert.ok(!JSON.stringify(safe).includes('fixture-secret')); assert.ok(!JSON.stringify(safe).includes('fixture-api'));
    const order = await makeOrder();
    await assert.rejects(beginIyzicoCheckout({ ...actor, id: other.id }, order.id, billing), { code: 'ORDER_NOT_FOUND' });
    const first = await beginIyzicoCheckout(actor, order.id, billing);
    assert.deepEqual(await beginIyzicoCheckout(actor, order.id, billing), first);
    assert.equal(requests.filter(v => v.path.includes('/initialize/')).length, 1);
    const session = await db.paymentCheckoutSession.findFirstOrThrow({ where: { orderId: order.id } });
    assert.ok(!session.contextCiphertext.includes(billing.identityNumber));
    await assert.rejects(iyzicoCallback(session.id, 'wrong'), { code: 'PAYMENT_CALLBACK_INVALID' });
    await assert.rejects(handleIyzicoWebhook({ paymentConversationId: session.attemptId, iyziEventType: 'CHECKOUT_FORM_AUTH', status: 'SUCCESS', token: session.token }, '0'.repeat(64)), { code: 'PAYMENT_SIGNATURE_INVALID' });
    const result = results.get(session.token!); results.set(session.token!, { ...result, currency: 'EUR' });
    await assert.rejects(iyzicoCallback(session.id, session.token), { code: 'PAYMENT_MISMATCH' });
    assert.equal(await db.agreement.count({ where: { customerId: owner.id } }), 0);
    results.set(session.token!, result);
    await Promise.all([iyzicoCallback(session.id, session.token), iyzicoCallback(session.id, session.token)]);
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: order.id } })).status, 'PAID');
    assert.equal(await db.agreement.count({ where: { customerId: owner.id } }), 1);

    const sub = await db.creditSubscription.create({ data: { customerId: owner.id, name: 'Monthly payment fixture', amount: '10', currency: 'TRY', credits: 10, periodMonths: 1, autoRenew: true, consentedAt: new Date(), nextPaymentOn: billingToday(), anchorOn: billingToday() } });
    const monthly = await makeOrder({ subscriptionId: sub.id, periodNumber: 1, kind: 'SUBSCRIPTION', periodMonths: 1, validityDays: null, renewalRequested: true });
    await assert.rejects(beginIyzicoCheckout(actor, monthly.id, { ...billing, renewalConsent: false }), { code: 'RENEWAL_CONSENT_REQUIRED' });
    await beginIyzicoCheckout(actor, monthly.id, billing);
    const monthlySession = await db.paymentCheckoutSession.findFirstOrThrow({ where: { orderId: monthly.id } });
    await iyzicoCallback(monthlySession.id, monthlySession.token);
    const active = await db.creditSubscription.findUniqueOrThrow({ where: { id: sub.id } });
    assert.ok(active.paymentMethodRef); assert.equal(active.status, 'ACTIVE');
    await assert.rejects(savePaymentSettings(admin, { provider: 'iyzico', enabled: false, recurringEnabled: true, mode: 'sandbox', publicUrl: settings.publicUrl, apiKey: 'different-key', secretKey: 'different-secret' }), { code: 'PAYMENT_ACCOUNT_IN_USE' });
    const stale = await db.creditPaymentAttempt.create({ data: { orderId: monthly.id, attemptNumber: 2, provider: 'iyzico', createdAt: new Date(Date.now() - 7200000) } });
    await assert.rejects(closeUnchargedPayment(admin, stale.id, { confirmedNoCharge: true, providerReference: 'Provider confirmed fixture' }), { code: 'PAYMENT_REVIEW_CHANGED' });
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: monthly.id } })).status, 'PAID');
    await db.creditPaymentAttempt.delete({ where: { id: stale.id } });
    // Move the next cycle to today without manufacturing a future charge date.
    await db.agreement.updateMany({ where: { customerId: owner.id }, data: { cancelledAt: new Date() } });
    await db.creditSubscription.update({ where: { id: sub.id }, data: { nextPaymentOn: billingToday(), anchorOn: billingToday(), anchorPeriod: 1 } });
    await runCreditRenewals(iyzicoRecurringProvider);
    assert.equal(requests.filter(v => v.path === '/payment/auth').length, 1);
    assert.equal(await db.creditOrder.count({ where: { subscriptionId: sub.id, status: 'PAID' } }), 2);
    await runCreditRenewals(iyzicoRecurringProvider);
    assert.equal(requests.filter(v => v.path === '/payment/auth').length, 1);
    await db.agreement.updateMany({ where: { customerId: owner.id }, data: { cancelledAt: new Date() } });
    await db.creditSubscription.update({ where: { id: sub.id }, data: { nextPaymentOn: billingToday(), anchorOn: billingToday(), anchorPeriod: 2 } });
    uncertain = true;
    await runCreditRenewals(iyzicoRecurringProvider);
    const count = requests.filter(v => v.path === '/payment/auth').length;
    await runCreditRenewals(iyzicoRecurringProvider);
    assert.equal(requests.filter(v => v.path === '/payment/auth').length, count, 'An unknown result must never trigger a second charge');
    await changeSubscription(actor, sub.id, 'stop');
    assert.equal((await db.creditSubscription.findUniqueOrThrow({ where: { id: sub.id } })).autoRenew, false);
    const declined = await makeOrder();
    await beginIyzicoCheckout(actor, declined.id, billing);
    const declinedSession = await db.paymentCheckoutSession.findFirstOrThrow({ where: { orderId: declined.id } });
    results.set(declinedSession.token!, { status: 'failure', errorCode: '10051' });
    const grants = await db.agreement.count({ where: { customerId: owner.id } });
    await iyzicoCallback(declinedSession.id, declinedSession.token);
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: declined.id } })).status, 'FAILED');
    assert.equal(await db.agreement.count({ where: { customerId: owner.id } }), grants);
    const noTokenSub = await db.creditSubscription.create({ data: { customerId: owner.id, name: 'No token fixture', amount: '10', currency: 'TRY', credits: 10, periodMonths: 1, autoRenew: true, consentedAt: new Date() } });
    const noTokenOrder = await makeOrder({ subscriptionId: noTokenSub.id, periodNumber: 1, kind: 'SUBSCRIPTION', periodMonths: 1, validityDays: null, renewalRequested: true });
    await beginIyzicoCheckout(actor, noTokenOrder.id, billing);
    const noTokenSession = await db.paymentCheckoutSession.findFirstOrThrow({ where: { orderId: noTokenOrder.id } });
    const withoutTokens = results.get(noTokenSession.token!); delete withoutTokens.cardToken; delete withoutTokens.cardUserKey;
    await iyzicoCallback(noTokenSession.id, noTokenSession.token);
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: noTokenOrder.id } })).status, 'PAID');
    assert.equal((await db.creditSubscription.findUniqueOrThrow({ where: { id: noTokenSub.id } })).autoRenew, false);
  } finally {
    globalThis.fetch = originalFetch; db.$transaction = originalTx; db.paymentGatewaySettings.findUnique = originalGateway;
    await db.paymentCheckoutSession.deleteMany({ where: { customerId: owner.id } });
    await db.paymentStoredMethod.deleteMany({ where: { customerId: owner.id } });
    await db.creditPaymentAttempt.deleteMany({ where: { order: { customerId: owner.id } } });
    await db.creditOrder.deleteMany({ where: { customerId: owner.id } });
    await db.creditSubscription.deleteMany({ where: { customerId: owner.id } });
    await db.agreement.deleteMany({ where: { customerId: owner.id } });
    await db.notification.deleteMany({ where: { userId: { in: [owner.id, other.id] } } });
    await db.activityLog.deleteMany({ where: { userId: { in: [owner.id, other.id] } } });
    await db.user.deleteMany({ where: { id: { in: [owner.id, other.id] } } });
    await db.$disconnect();
  }
});
