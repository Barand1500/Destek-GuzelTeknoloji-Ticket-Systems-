import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { db } from '../src/config/db.js';
import type { Actor } from '../src/types/express.js';
import { agreementInput, createAgreement, cancelAgreement, reactivateAgreement, deleteAgreement, updateAgreement, listAgreements, setCustomerParent, setCompanyCreditSharing, debitResolution } from '../src/services/agreements.service.js';
import { visibility, updateConversation, addMessage } from '../src/services/conversations.service.js';

test('Agreements preserve dated purchases, enforce family scope and debit atomically exactly once', async () => {
  assert.equal(agreementInput.safeParse({ name: 'x', startsOn: '2026-02-30', endsOn: '2027-01-01', fee: '100', credits: 1, type: 'MONTHLY' }).success, false);
  const suffix = randomUUID();
  const users = await Promise.all(['ADMIN', 'CUSTOMER', 'CUSTOMER', 'CUSTOMER', 'CUSTOMER'].map((role, i) => db.user.create({ data: { role: role as 'ADMIN' | 'CUSTOMER', name: `Agreement fixture ${suffix} ${i}`, passwordHash: 'fixture' } })));
  const [staff, parent, child, stranger, sibling] = users;
  const actor: Actor = { id: staff.id, name: staff.name, email: '', role: 'ADMIN', departmentIds: [], sessionId: '' };
  const client: Actor = { ...actor, id: parent.id, role: 'CUSTOMER' };
  const department = await db.department.create({ data: { name: `Agreement ${suffix}` } });
  const tickets: string[] = [];
  try {
    await setCustomerParent(actor, child.id, parent.id);
    await setCustomerParent(actor, sibling.id, parent.id);
    await assert.rejects(setCustomerParent(actor, parent.id, child.id));
    await assert.rejects(setCustomerParent(actor, parent.id, parent.id));
    await assert.rejects(createAgreement(client, parent.id, { name: 'Denied', type: 'ONE_OFF', startsOn: '2020-01-01', endsOn: '2099-01-01', fee: '10', credits: 10 }));
    const a = await createAgreement(actor, parent.id, { name: 'Maintenance', type: 'YEARLY', startsOn: '2020-01-01', endsOn: '2099-01-01', fee: '1234.50', credits: 10 });
    await assert.rejects(createAgreement(actor, child.id, { name: 'Child credit', type: 'ONE_OFF', startsOn: '2020-01-01', endsOn: '2099-01-01', fee: '25', credits: 3 }));
    const childActor = { ...client, id: child.id };
    const childSummary = await listAgreements(childActor, child.id);
    assert.equal(childSummary.availableCredits, 10);
    assert.equal(childSummary.personalCredits, 0);
    assert.equal(childSummary.agreements[0].customerId, parent.id);
    const sharedSoon = await createAgreement(actor, parent.id, { name: 'Shared sooner', type: 'ONE_OFF', startsOn: '2020-01-01', endsOn: '2028-01-01', fee: '0', credits: 2 });
    assert.equal((await listAgreements(childActor, child.id)).agreements.filter(a => a.usable)[0].id, sharedSoon.id);
    await cancelAgreement(actor, parent.id, sharedSoon.id);
    await assert.rejects(reactivateAgreement(client, parent.id, sharedSoon.id));
    await assert.rejects(reactivateAgreement(actor, stranger.id, sharedSoon.id));
    await reactivateAgreement(actor, parent.id, sharedSoon.id);
    await assert.rejects(reactivateAgreement(actor, parent.id, sharedSoon.id));
    await cancelAgreement(actor, parent.id, sharedSoon.id);
    await assert.rejects(setCompanyCreditSharing(client, parent.id, false));
    await assert.rejects(setCompanyCreditSharing(actor, parent.id, false));
    await assert.rejects(listAgreements(childActor, sibling.id));
    const expired = await createAgreement(actor, parent.id, { name: 'Expired', type: 'MONTHLY', startsOn: '2020-01-01', endsOn: '2020-02-01', fee: '50', credits: 20 });
    const balance = await listAgreements(client, parent.id);
    assert.equal(balance.availableCredits, 10);
    await assert.rejects(listAgreements({ ...client, id: stranger.id }, parent.id));
    const make = async () => { const t = await db.conversation.create({ data: { customerId: child.id, departmentId: department.id, subject: 'Credit test', searchSubject: 'credit test', channel: 'TICKET' } }); tickets.push(t.id); return t; };
    const first = await make();
    await assert.rejects(db.$transaction(async tx => {
      await debitResolution(tx, actor, first, { agreementId: a.id, credits: 1 });
      throw new Error('company-allowed-rollback');
    }), /company-allowed-rollback/);
    assert.equal(await db.creditCharge.count({ where: { conversationId: first.id } }), 0);
    await assert.rejects(addMessage(client, first.id, { body: 'Parent must be read only' }), (e: any) => e.code === 'TICKET_UNAVAILABLE');
    await assert.rejects(db.$transaction(tx => debitResolution(tx, actor, first, { agreementId: expired.id, credits: 1 })));
    assert.equal((await db.agreement.findUniqueOrThrow({ where: { id: expired.id } })).usedCredits, 0);
    assert.equal(await db.conversation.count({ where: { AND: [visibility({ ...client, id: child.id }), { customerId: parent.id }] } }), 0);
    await assert.rejects(updateConversation(actor, first.id, { status: 'RESOLVED' }), (e: any) => e.code === 'CREDIT_REQUIRED');
    await assert.rejects(db.$transaction(tx => debitResolution(tx, actor, { ...first, customerId: stranger.id }, { agreementId: a.id, credits: 1 })));
    const attempts = await Promise.allSettled([first, await make()].map(t => db.$transaction(tx => debitResolution(tx, actor, t, { agreementId: a.id, credits: 7 }))));
    assert.equal(attempts.filter(x => x.status === 'fulfilled').length, 1);
    const charge = await db.creditCharge.findFirstOrThrow({ where: { agreementId: a.id } });
    assert.equal((await listAgreements(childActor, child.id)).charges.some(row => row.id === charge.id), true);
    assert.equal((await listAgreements(client, parent.id)).charges.some(row => row.id === charge.id), true);
    assert.equal((await listAgreements({ ...client, id: sibling.id }, sibling.id)).charges.some(row => row.id === charge.id), false);
    await db.$transaction(tx => debitResolution(tx, actor, { id: charge.conversationId, customerId: child.id }, { agreementId: a.id, credits: 7 }));
    assert.equal(await db.creditCharge.count({ where: { agreementId: a.id } }), 1);
    const chargedTicket = await db.conversation.findUniqueOrThrow({ where: { id: charge.conversationId } });
    await updateConversation(actor, chargedTicket.id, { status: 'RESOLVED' });
    await updateConversation(actor, chargedTicket.id, { status: 'OPEN' });
    await updateConversation(actor, chargedTicket.id, { status: 'RESOLVED' });
    assert.equal((await db.agreement.findUniqueOrThrow({ where: { id: a.id } })).usedCredits, 7);
    const last = await make();
    await updateConversation(actor, last.id, { status: 'RESOLVED', creditResolution: { agreementId: a.id, credits: 3 } });
    assert.equal((await listAgreements(client, parent.id)).availableCredits, 0);
    assert.equal(await db.conversation.count({ where: { AND: [visibility(client), { id: last.id }] } }), 1);
    assert.equal(await db.conversation.count({ where: { AND: [visibility({ ...client, id: stranger.id }), { id: last.id }] } }), 0);
    const changes = { name: 'Updated maintenance', type: 'YEARLY', startsOn: '2020-01-01', endsOn: '2098-01-01', credits: 12 };
    await assert.rejects(updateAgreement(client, parent.id, a.id, changes));
    await assert.rejects(updateAgreement(actor, stranger.id, a.id, changes));
    await assert.rejects(updateAgreement(actor, parent.id, a.id, { ...changes, credits: 9 }));
    await updateAgreement(actor, parent.id, a.id, changes);
    const edited = await db.agreement.findUniqueOrThrow({ where: { id: a.id } });
    assert.equal(edited.usedCredits, 10); assert.equal(edited.name, changes.name);
    assert.equal(edited.fee.toString(), '1234.5');
    assert.equal((await listAgreements(actor, child.id)).sharedCredits, 2);
    await updateAgreement(actor, parent.id, a.id, { ...changes, credits: 10 });
    await assert.rejects(deleteAgreement(client, parent.id, a.id));
    await assert.rejects(deleteAgreement({ ...actor, role: 'AGENT', rolePermissions: ['customers.update'] }, parent.id, a.id));
    await assert.rejects(deleteAgreement(actor, stranger.id, a.id));
    await assert.rejects(deleteAgreement({ ...actor, role: 'AGENT', rolePermissions: ['customers.view'] }, parent.id, a.id));
    const removable = await createAgreement(actor, parent.id, { name: 'Remove remaining balance', type: 'ONE_OFF', startsOn: '2020-01-01', endsOn: '2099-01-01', fee: '0', credits: 4 });
    assert.equal((await listAgreements(actor, child.id)).sharedCredits, 4);
    await deleteAgreement({ ...actor, role: 'AGENT', rolePermissions: ['customers.delete'] }, parent.id, removable.id);
    assert.equal((await listAgreements(actor, child.id)).sharedCredits, 0);
    const unusedAttempt = await make();
    await assert.rejects(db.$transaction(tx => debitResolution(tx, actor, unusedAttempt, { agreementId: removable.id, credits: 1 })));
    const chargeCount = await db.creditCharge.count({ where: { agreementId: a.id } });
    await cancelAgreement(actor, parent.id, a.id);
    await reactivateAgreement(actor, parent.id, a.id);
    assert.equal((await db.agreement.findUniqueOrThrow({ where: { id: a.id } })).usedCredits, 10);
    await deleteAgreement(actor, parent.id, a.id);
    await assert.rejects(reactivateAgreement(actor, parent.id, a.id));
    assert.equal((await listAgreements(actor, child.id)).agreements.some(row => row.id === a.id), false);
    assert.equal(await db.creditCharge.count({ where: { agreementId: a.id } }), chargeCount);
    assert.equal((await listAgreements(actor, parent.id)).charges.some(row => row.agreement?.id === a.id), true);
    const deletedAttempt = await make();
    await assert.rejects(db.$transaction(tx => debitResolution(tx, actor, deletedAttempt, { agreementId: a.id, credits: 1 })));
    await cancelAgreement(actor, parent.id, expired.id);
    await reactivateAgreement(actor, parent.id, expired.id);
    const restoredExpired = (await listAgreements(actor, parent.id)).agreements.find(row => row.id === expired.id)!;
    assert.equal(restoredExpired.state, 'EXPIRED'); assert.equal(restoredExpired.usable, false);
    await deleteAgreement(actor, parent.id, expired.id);
    await assert.rejects(updateAgreement(actor, parent.id, expired.id, changes));
    assert.equal((await listAgreements(actor, parent.id)).agreements.some(row => row.id === expired.id), false);
    assert.equal(await db.activityLog.count({ where: { entityId: a.id, action: 'agreement.deleted' } }), 1);
  } finally {
    await db.creditCharge.deleteMany({ where: { conversationId: { in: tickets } } });
    await db.agreement.deleteMany({ where: { customerId: { in: users.map(x => x.id) } } });
    await db.conversationMessage.deleteMany({ where: { conversationId: { in: tickets } } });
    await db.conversation.deleteMany({ where: { id: { in: tickets } } });
    await db.activityLog.deleteMany({ where: { userId: { in: users.map(x => x.id) } } });
    await db.user.updateMany({ where: { id: { in: users.map(x => x.id) } }, data: { parentCustomerId: null } });
    await db.session.deleteMany({ where: { userId: { in: users.map(x => x.id) } } });
    await db.user.deleteMany({ where: { id: { in: users.map(x => x.id) } } });
    await db.department.delete({ where: { id: department.id } });
    await db.$disconnect();
  }
});
