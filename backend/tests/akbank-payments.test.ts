import 'dotenv/config';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { db } from '../src/config/db.js';
import { openPayment, sealPayment } from '../src/services/payment-secrets.js';
import { akbankHash } from '../src/services/akbank-client.js';
import { beginAkbankCheckout, akbankCallback, reconcileAkbankSession, runAkbankPaymentChecks } from '../src/services/akbank-payments.service.js';
import { startPaymentReversal, reconcilePaymentReversal, closeUnrefundedReversal } from '../src/services/payment-reversals.service.js';
import { closeUnchargedPayment } from '../src/services/payment-operations.service.js';
import { saveAkbankSettings } from '../src/services/akbank-settings.service.js';

test('Akbank bank ledger settles once, isolates card data, queries uncertain refunds and preserves credit history', async () => {
  const owner = await db.user.create({ data: { name: 'Akbank fixture ' + randomUUID(), role: 'CUSTOMER', passwordHash: 'fixture' } });
  const actor = { id: owner.id, name: owner.name, role: 'CUSTOMER' as const, email: '', departmentIds: [], sessionId: '', ipAddress: '127.0.0.1' };
  const admin = { ...actor, role: 'ADMIN' as const };
  const config = { merchantSafeId: 'fixture-merchant', terminalSafeId: 'fixture-terminal', secretKey: 'fixture-secret', mode: 'sandbox' as const };
  const card = { holder: 'TEST USER', number: '4111111111111111', expiry: '1230', cvc: '123' };
  const settings = { id: 'akbank', enabled: true, mode: 'sandbox', testedAt: new Date(), fingerprint: 'fixture', publicUrl: 'https://akbank.example.invalid', credentialsCiphertext: sealPayment(config) };
  const originalFetch = globalThis.fetch, originalTx = db.$transaction, originalGateway = db.paymentGatewaySettings.findUnique;
  const gateway = async ({ where }: any) => where.id === 'akbank' ? settings : null;
  db.paymentGatewaySettings.findUnique = gateway as any;
  db.$transaction = ((callback: any, options: any) => originalTx.call(db, (tx: any) => { tx.paymentGatewaySettings.findUnique = gateway; return callback(tx); }, options)) as typeof originalTx;
  const ledger = new Map<string, any[]>(), calls: any[] = [];
  let queryUnavailable = false, uncertainRefund = false, refundDeclined = false;
  globalThis.fetch = (async (_url: any, init: any) => {
    const body = JSON.parse(init.body); calls.push(body);
    assert.equal(init.headers['auth-hash'], akbankHash(init.body, config.secretKey));
    assert.equal(body.card, undefined);
    if (queryUnavailable) throw Error('simulated provider outage');
    const id = body.order.orderId, rows = ledger.get(id) ?? [];
    if (body.txnCode === '1002' && refundDeclined) {
      const text = JSON.stringify({ responseCode: 'VPS-1021', txnCode: '1002', terminal: body.terminal, order: { orderId: id } });
      return new Response(text, { headers: { 'auth-hash': akbankHash(text, config.secretKey) } });
    }
    if (body.txnCode === '1002') {
      rows.push({ orderId: randomUUID(), orgOrderId: id, txnCode: '1002', responseCode: 'VPS-0000', hostResponseCode: '00', txnStatus: 'N', amount: body.transaction.amount, currencyCode: 949, rrn: randomUUID(), stan: rows.length + 1 });
      ledger.set(id, rows);
      if (uncertainRefund) throw Error('response lost after refund');
    }
    if (body.txnCode === '1003') rows[0].txnStatus = 'V';
    const value = { responseCode: 'VPS-0000', txnCode: body.txnCode, terminal: body.terminal, ...(body.txnCode === '1010' ? { txnDetailList: rows } : { order: { orderId: id } }) };
    const text = JSON.stringify(value);
    return new Response(text, { headers: { 'auth-hash': akbankHash(text, config.secretKey) } });
  }) as typeof fetch;
  const makeOrder = async (extra: any = {}) => db.creditOrder.create({ data: { customerId: owner.id, requestedById: owner.id, requestKey: randomUUID(), inputHash: 'a'.repeat(64), kind: 'TOP_UP', name: 'Akbank fixture', credits: 100, total: '100', currency: 'TRY', validityDays: 365, ...extra } });
  function callback(fields: Record<string, string>, extra: any = {}) {
    const value: Record<string, string> = { txnCode: '1000', responseCode: 'VPS-0000', hostResponseCode: '00', merchantSafeId: config.merchantSafeId, terminalSafeId: config.terminalSafeId, orderId: fields.orderId, amount: fields.amount, installCount: '1', ...extra };
    value.hashParams = Object.keys(value).join('+'); value.hash = akbankHash(value.hashParams.split('+').map(k => value[k]).join(''), config.secretKey); return value;
  }
  function paid(fields: Record<string, string>) { ledger.set(fields.orderId, [{ orderId: fields.orderId, orgOrderId: fields.orderId, txnCode: '1000', responseCode: 'VPS-0000', hostResponseCode: '00', txnStatus: 'N', amount: fields.amount, currencyCode: 949, installCount: 1, rrn: randomUUID(), stan: 1 }]); }
  try {
    const order = await makeOrder();
    await assert.rejects(beginAkbankCheckout({ ...actor, id: randomUUID() }, order.id, { card }), { code: 'INACTIVE_CUSTOMER' });
    const form = await beginAkbankCheckout(actor, order.id, { card });
    const session = await db.paymentCheckoutSession.findUniqueOrThrow({ where: { attemptId: form.fields.orderId } });
    assert.equal(new URL(form.fields.okUrl).pathname, '/api/v1/payments/akbank/callback/' + session.id);
    assert.deepEqual(openPayment(session.contextCiphertext), { config });
    const logs = await db.activityLog.findMany({ where: { userId: owner.id } });
    assert.ok(!JSON.stringify(logs).includes(card.number));
    await assert.rejects(beginAkbankCheckout(actor, order.id, { card }), { code: 'PAYMENT_IN_PROGRESS' });
    await assert.rejects(akbankCallback(session.id, { ...callback(form.fields), hash: 'bad' }), { code: 'PAYMENT_CALLBACK_INVALID' });
    await reconcileAkbankSession(session.id);
    assert.equal(await db.agreement.count({ where: { customerId: owner.id } }), 0);
    paid(form.fields);
    ledger.get(form.fields.orderId)![0].amount = '101';
    await assert.rejects(reconcileAkbankSession(session.id), { code: 'PAYMENT_MISMATCH' });
    ledger.get(form.fields.orderId)![0].amount = '100';
    await Promise.all([akbankCallback(session.id, callback(form.fields)), akbankCallback(session.id, callback(form.fields))]);
    assert.equal(await db.agreement.count({ where: { customerId: owner.id } }), 1);
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: order.id } })).status, 'PAID');
    const grant = await db.agreement.findFirstOrThrow({ where: { customerId: owner.id } });
    await db.agreement.update({ where: { id: grant.id }, data: { usedCredits: 10 } });
    await assert.rejects(startPaymentReversal(admin, order.id, { requestKey: randomUUID(), kind: 'REFUND', credits: 91, reason: 'Too much fixture' }), { code: 'REFUND_NOT_ALLOWED' });
    const request = { requestKey: randomUUID(), kind: 'REFUND', credits: 20, reason: 'Partial fixture' };
    const reversal = await startPaymentReversal(admin, order.id, request);
    assert.equal(reversal.status, 'SUCCEEDED');
    await startPaymentReversal(admin, order.id, request);
    assert.equal(calls.filter(v => v.txnCode === '1002').length, 1);
    uncertainRefund = true;
    const uncertain = await startPaymentReversal(admin, order.id, { ...request, requestKey: randomUUID(), credits: 10 });
    assert.equal(uncertain.status, 'REVIEW');
    await Promise.all([reconcilePaymentReversal(uncertain.id), reconcilePaymentReversal(uncertain.id)]);
    assert.equal((await db.paymentReversal.findUniqueOrThrow({ where: { id: uncertain.id } })).status, 'SUCCEEDED');
    assert.equal(calls.filter(v => v.txnCode === '1002').length, 2);
    assert.equal((await db.agreement.findUniqueOrThrow({ where: { id: grant.id } })).credits, 70);
    await akbankCallback(session.id, callback(form.fields));
    assert.equal(await db.agreement.count({ where: { customerId: owner.id } }), 1);
    uncertainRefund = false;
    refundDeclined = true;
    const declinedRefund = await startPaymentReversal(admin, order.id, { ...request, requestKey: randomUUID(), credits: 5 });
    assert.equal(declinedRefund.status, 'FAILED');
    assert.equal(declinedRefund.failureCode, 'VPS-1021');
    assert.equal((await db.agreement.findUniqueOrThrow({ where: { id: grant.id } })).credits, 70);
    refundDeclined = false;
    queryUnavailable = true;
    const unsent = await startPaymentReversal(admin, order.id, { ...request, requestKey: randomUUID(), credits: 5 });
    assert.equal(unsent.status, 'REVIEW');
    assert.equal((await db.agreement.findUniqueOrThrow({ where: { id: grant.id } })).credits, 65);
    await db.paymentReversal.update({ where: { id: unsent.id }, data: { createdAt: new Date(Date.now() - 7200000) } });
    await closeUnrefundedReversal(admin, unsent.id, { confirmedNoRefund: true, providerReference: 'Bank confirmed no refund fixture' });
    assert.equal((await db.agreement.findUniqueOrThrow({ where: { id: grant.id } })).credits, 70);
    queryUnavailable = false;
    const fullRefundOrder = await makeOrder();
    const fullRefundForm = await beginAkbankCheckout(actor, fullRefundOrder.id, { card }); paid(fullRefundForm.fields);
    const fullRefundSession = await db.paymentCheckoutSession.findUniqueOrThrow({ where: { attemptId: fullRefundForm.fields.orderId } });
    await akbankCallback(fullRefundSession.id, callback(fullRefundForm.fields));
    const fullRefund = await startPaymentReversal(admin, fullRefundOrder.id, { ...request, requestKey: randomUUID(), credits: 100 });
    assert.equal(fullRefund.status, 'SUCCEEDED');
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: fullRefundOrder.id } })).status, 'REFUNDED');
    const cancelledOrder = await makeOrder();
    const cancelForm = await beginAkbankCheckout(actor, cancelledOrder.id, { card }); paid(cancelForm.fields);
    const cancelSession = await db.paymentCheckoutSession.findUniqueOrThrow({ where: { attemptId: cancelForm.fields.orderId } });
    await akbankCallback(cancelSession.id, callback(cancelForm.fields));
    const cancel = await startPaymentReversal(admin, cancelledOrder.id, { requestKey: randomUUID(), kind: 'CANCEL', credits: 100, reason: 'Bank cancel fixture' });
    assert.equal(cancel.status, 'SUCCEEDED');
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: cancelledOrder.id } })).status, 'REFUNDED');
    const pendingOrder = await makeOrder();
    const pendingForm = await beginAkbankCheckout(actor, pendingOrder.id, { card });
    queryUnavailable = true;
    await runAkbankPaymentChecks();
    await assert.rejects(beginAkbankCheckout(actor, pendingOrder.id, { card }), { code: 'PAYMENT_IN_PROGRESS' });
    await assert.rejects(saveAkbankSettings(admin, { mode: 'sandbox', secretKey: 'new-key', publicUrl: settings.publicUrl }), { code: 'PAYMENT_ACCOUNT_IN_USE' });
    await db.creditPaymentAttempt.update({ where: { id: pendingForm.fields.orderId }, data: { createdAt: new Date(Date.now() - 7200000) } });
    await closeUnchargedPayment(admin, pendingForm.fields.orderId, { confirmedNoCharge: true, providerReference: 'Confirmed no bank charge fixture' });
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: pendingOrder.id } })).status, 'FAILED');
    queryUnavailable = false;
    const declineOrder = await makeOrder();
    const declineForm = await beginAkbankCheckout(actor, declineOrder.id, { card });
    const declineSession = await db.paymentCheckoutSession.findUniqueOrThrow({ where: { attemptId: declineForm.fields.orderId } });
    await akbankCallback(declineSession.id, callback(declineForm.fields, { responseCode: 'VPS-0051', hostResponseCode: '51' }));
    assert.equal((await db.creditOrder.findUniqueOrThrow({ where: { id: declineOrder.id } })).status, 'FAILED');
    const sub = await db.creditSubscription.create({ data: { customerId: owner.id, name: 'Akbank plan fixture', credits: 100, amount: '100', currency: 'TRY', periodMonths: 1, autoRenew: true, consentedAt: new Date() } });
    const plan = await makeOrder({ subscriptionId: sub.id, kind: 'SUBSCRIPTION', periodNumber: 1, periodMonths: 1, validityDays: null, renewalRequested: true });
    await assert.rejects(beginAkbankCheckout(actor, plan.id, { card }), { code: 'MANUAL_RENEWAL_CONSENT_REQUIRED' });
    const planForm = await beginAkbankCheckout(actor, plan.id, { card, manualRenewalConsent: true });
    assert.equal((await db.creditSubscription.findUniqueOrThrow({ where: { id: sub.id } })).autoRenew, false);
    paid(planForm.fields);
    const planSession = await db.paymentCheckoutSession.findUniqueOrThrow({ where: { attemptId: planForm.fields.orderId } });
    await akbankCallback(planSession.id, callback(planForm.fields));
    assert.equal((await db.creditSubscription.findUniqueOrThrow({ where: { id: sub.id } })).nextPaymentOn, null);
  } finally {
    globalThis.fetch = originalFetch; db.$transaction = originalTx; db.paymentGatewaySettings.findUnique = originalGateway;
    await db.paymentReversal.deleteMany({ where: { order: { customerId: owner.id } } });
    await db.paymentCheckoutSession.deleteMany({ where: { customerId: owner.id } });
    await db.creditPaymentAttempt.deleteMany({ where: { order: { customerId: owner.id } } });
    await db.creditOrder.deleteMany({ where: { customerId: owner.id } });
    await db.creditSubscription.deleteMany({ where: { customerId: owner.id } });
    await db.agreement.deleteMany({ where: { customerId: owner.id } });
    await db.notification.deleteMany({ where: { userId: owner.id } });
    await db.activityLog.deleteMany({ where: { userId: owner.id } });
    await db.user.delete({ where: { id: owner.id } });
    await db.$disconnect();
  }
});
