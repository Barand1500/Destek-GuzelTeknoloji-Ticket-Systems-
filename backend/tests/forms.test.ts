import 'dotenv/config';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import type { AddressInfo } from 'node:net';
import { db } from '../src/config/db.js';
import { env } from '../src/config/env.js';
import { app } from '../src/app.js';
import { authorizeForm, formTokenHash, issueFormLink } from '../src/services/form-access.service.js';
import { submitForm, formSubmissionSchema, saveFormSettings } from '../src/services/forms.service.js';
import { addMessage, listConversations } from '../src/services/conversations.service.js';
import { persistInboundEmail } from '../src/services/inbound-email.service.js';
import type { Actor } from '../src/types/express.js';
import { discardStoredUploads } from '../src/services/uploads.service.js';
import { requestFormLogin, verifyFormLogin } from '../src/services/form-login.service.js';

test('Form submissions, private guest access, replies, attachments and email threading stay in their own ticket', async t => {
  const suffix = randomUUID(), email = `form-${suffix}@example.invalid`;
  const department = await db.department.create({ data: { name: `Form test ${suffix}` } });
  const destination = await db.department.create({ data: { name: `Form destination ${suffix}` } });
  const inactive = await db.department.create({ data: { name: `Form inactive ${suffix}`, isActive: false } });
  const customer = await db.user.create({ data: { name: `Existing ${suffix}`, email, company: 'Original company', role: 'CUSTOMER', passwordHash: 'test' } });
  const staff = await db.user.create({ data: { name: `Staff ${suffix}`, role: 'ADMIN', passwordHash: 'test' } });
  const actor: Actor = { id: staff.id, name: staff.name, role: 'ADMIN', email: '', departmentIds: [], sessionId: '' };
  const originalSettings = await db.formSettings.findUnique({ where: { id: 'default' } });
  const enabled = env.TURNSTILE_ENABLED;
  const originalSmtp = db.integrationSettings.findUnique.bind(db.integrationSettings);
  const originalTx = db.$transaction.bind(db);
  // Keep fixture mail jobs unavailable to any local background worker. No provider sends.
  const smtp = (value: any) => ({ ...value, smtpEnabled: true, smtpHost: 'smtp.example.invalid', smtpFromAddress: 'support@example.invalid' });
  db.$transaction = ((work: any, options?: any) => originalTx(async tx => {
    const findSettings = tx.integrationSettings.findUnique.bind(tx.integrationSettings);
    tx.integrationSettings.findUnique = ((args: any) => findSettings(args).then(smtp)) as typeof findSettings;
    const upsert = tx.outboundMessage.upsert.bind(tx.outboundMessage), create = tx.outboundMessage.create.bind(tx.outboundMessage);
    tx.outboundMessage.upsert = ((args: any) => upsert({ ...args, create: { ...args.create, availableAt: new Date('2099-01-01') } })) as typeof upsert;
    tx.outboundMessage.create = ((args: any) => create({ ...args, data: { ...args.data, availableAt: new Date('2099-01-01') } })) as typeof create;
    return work(tx);
  }, options)) as typeof db.$transaction;
  db.integrationSettings.findUnique = ((args: any) => originalSmtp(args).then(smtp)) as typeof originalSmtp;
  const server = app.listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  const url = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api/v1/public/form`;
  const ids: string[] = [], extraUsers: string[] = [];
  try {
    env.TURNSTILE_ENABLED = false;
    await db.formSettings.upsert({ where: { id: 'default' }, create: { enabled: true, departmentId: destination.id, title: 'Form' }, update: { enabled: true, departmentId: destination.id } });
    assert.equal(formSubmissionSchema.safeParse({ name: 'No department needed', email, subject: 'x', message: 'x' }).success, true);
    assert.equal(formSubmissionSchema.safeParse({ name: 'GSM only', email, phone: '2121234567', subject: 'x', message: 'x' }).success, false);
    assert.equal(formSubmissionSchema.parse({ name: 'GSM', email, phone: '+90 530 411 21 50', subject: 'x', message: 'x' }).phone, '5304112150');
    const publicSettings = (await (await fetch(`${url}/settings`)).json()).data;
    assert.equal(publicSettings.departments, undefined);
    assert.equal(publicSettings.departmentId, undefined);
    assert.equal(publicSettings.maxTotalFileSize, 30 * 1024 * 1024);
    const input = formSubmissionSchema.parse({ name: 'Submitted name', email, company: 'Submitted company', departmentId: department.id, subject: 'x', message: 'Initial request' });
    await assert.rejects(saveFormSettings(actor, { enabled: true, title: 'Form', departmentId: inactive.id }), error => (error as { code: string }).code === 'INVALID_DEPARTMENT');
    await db.formSettings.update({ where: { id: 'default' }, data: { departmentId: inactive.id } });
    await assert.rejects(submitForm(input), error => (error as { code: string }).code === 'FORM_UNAVAILABLE');
    await db.formSettings.update({ where: { id: 'default' }, data: { departmentId: destination.id } });
    const result = await submitForm(input);
    const ticket = await db.conversation.findUniqueOrThrow({ where: { number: result.number }, include: { formRequest: true } }); ids.push(ticket.id);
    assert.equal(ticket.customerId, customer.id);
    assert.equal(ticket.departmentId, destination.id);
    const saved = await saveFormSettings(actor, { enabled: true, title: 'Form', departmentId: destination.id });
    assert.deepEqual(saved, { enabled: true, title: 'Form', departmentId: destination.id });
    assert.equal((await db.formSettings.findUniqueOrThrow({ where: { id: 'default' } })).departmentId, destination.id);
    assert.equal(ticket.channel, 'FORM'); assert.deepEqual(ticket.replyChannels, ['FORM']);
    assert.equal(ticket.formRequest?.company, 'Submitted company');
    assert.equal((await db.user.findUniqueOrThrow({ where: { id: customer.id } })).company, 'Original company');
    const blankCompany = await db.user.create({ data: { name: 'Missing company', email: `blank-${email}`, role: 'CUSTOMER', passwordHash: 'test' } });
    extraUsers.push(blankCompany.id);
    for (const company of ['Submitted company', 'Replacement company', '']) {
      const submitted = await submitForm({ ...input, email: blankCompany.email!, company });
      const created = await db.conversation.findUniqueOrThrow({ where: { number: submitted.number } });
      ids.push(created.id);
      assert.equal(created.customerId, blankCompany.id);
      assert.equal((await db.user.findUniqueOrThrow({ where: { id: blankCompany.id } })).company, 'Submitted company');
    }
    assert.equal((await listConversations(actor, { page: 1, limit: 10, view: 'all', category: 'FORM', customerId: customer.id })).data[0].id, ticket.id);
    assert.equal((await listConversations(actor, { page: 1, limit: 10, view: 'all', category: 'FORM', customerId: customer.id, search: 'Submitted company' })).data[0].id, ticket.id);
    const ack = await db.outboundMessage.findFirstOrThrow({ where: { conversationId: ticket.id } });
    const link = String((ack.payload as { text: string }).text).match(/https?:\/\/\S+\/form\/talep#([a-f0-9]{64})/)![1];
    assert.equal((await authorizeForm(link)).id, ticket.id);
    assert.equal(await db.formAccess.count({ where: { tokenHash: link } }), 0);
    assert.equal(await db.formAccess.count({ where: { tokenHash: formTokenHash(link) } }), 1);
    await addMessage(actor, ticket.id, { body: 'INTERNAL SECRET', type: 'INTERNAL_NOTE' });
    await addMessage(actor, ticket.id, { body: 'Staff answer' });
    await db.conversation.update({ where: { id: ticket.id }, data: { replyChannels: ['EMAIL'] } });
    const emailOnly = await addMessage(actor, ticket.id, { body: 'EMAIL ONLY PRIVATE TO THAT CHANNEL' });
    assert.equal(emailOnly.visibleInForm, false);
    const emailJob = await db.outboundMessage.findFirstOrThrow({ where: { dedupeKey: `${emailOnly.id}:EMAIL` } });
    assert(String((emailJob.payload as { text: string }).text).includes('EMAIL ONLY PRIVATE TO THAT CHANNEL'));
    const emailFile = await db.conversationAttachment.create({ data: { uploaderId: staff.id, messageId: emailOnly.id, storageKey: randomUUID(), originalName: 'email-only.txt', mimeType: 'text/plain', size: 1 } });
    await db.conversation.update({ where: { id: ticket.id }, data: { replyChannels: ['TICKET'] } });
    await addMessage(actor, ticket.id, { body: 'PHONE ONLY' });
    await db.conversation.update({ where: { id: ticket.id }, data: { replyChannels: ['EMAIL', 'FORM'] } });
    const shared = await addMessage(actor, ticket.id, { body: 'FORM AND EMAIL' });
    assert.equal(shared.visibleInForm, true);
    await db.conversation.update({ where: { id: ticket.id }, data: { replyChannels: ['EMAIL'] } });
    const header = { 'x-form-token': link };
    const read = await fetch(`${url}/conversation`, { headers: header });
    assert.equal(read.status, 200);
    const body = await read.json();
    assert(!JSON.stringify(body).includes('INTERNAL SECRET'));
    assert(!JSON.stringify(body).includes('passwordHash'));
    assert(!JSON.stringify(body).includes('staffNote'));
    assert(body.data.messages.some((item: { body: string }) => item.body === 'Staff answer'));
    assert(body.data.messages.some((item: { body: string }) => item.body === 'FORM AND EMAIL'));
    assert(!JSON.stringify(body).includes('EMAIL ONLY PRIVATE TO THAT CHANNEL'));
    assert(!JSON.stringify(body).includes('PHONE ONLY'));
    assert(!JSON.stringify(body).includes('email-only.txt'));
    assert.equal((await fetch(`${url}/conversation/attachments/${emailFile.id}`, { headers: header })).status, 404);
    assert.equal((await fetch(`${url}/conversation?before=${emailOnly.id}`, { headers: header })).status, 400);
    assert.equal((await fetch(`${url}/conversation?after=${emailOnly.id}`, { headers: header })).status, 400);
    const visibleFirst = body.data.messages[0].id;
    const incremental = await (await fetch(`${url}/conversation?after=${visibleFirst}`, { headers: header })).json();
    assert(!JSON.stringify(incremental).includes('EMAIL ONLY PRIVATE TO THAT CHANNEL'));
    assert(incremental.data.messages.some((item: { body: string }) => item.body === 'FORM AND EMAIL'));
    // Switching back to Form must not reveal old email-only messages.
    await db.conversation.update({ where: { id: ticket.id }, data: { replyChannels: ['FORM'] } });
    assert(!JSON.stringify(await (await fetch(`${url}/conversation`, { headers: header })).json()).includes('EMAIL ONLY PRIVATE TO THAT CHANNEL'));
    const message = new FormData(); message.set('body', 'Guest answer');
    message.append('files', new Blob(['Form attachment'], { type: 'text/plain' }), 'form-test.txt');
    const reply = await fetch(`${url}/conversation/messages`, { method: 'POST', headers: header, body: message });
    assert.equal(reply.status, 201);
    assert.equal(await db.conversationMessage.count({ where: { conversationId: ticket.id, body: 'Guest answer', type: 'CUSTOMER_MESSAGE' } }), 1);
    const attachment = await db.conversationAttachment.findFirstOrThrow({ where: { message: { conversationId: ticket.id, body: 'Guest answer' } } });
    const download = await fetch(`${url}/conversation/attachments/${attachment.id}`, { headers: header });
    assert.equal(download.status, 200); assert.equal(await download.text(), 'Form attachment');
    const badFile = new FormData(); badFile.set('body', ''); badFile.append('files', new Blob(['<script>bad</script>'], { type: 'text/html' }), 'bad.html');
    assert.equal((await fetch(`${url}/conversation/messages`, { method: 'POST', headers: header, body: badFile })).status, 400);
    assert.equal((await fetch(`${url}/conversation`)).status, 401);
    assert.equal((await fetch(`${url}/conversation`, { headers: { 'x-form-token': 'a'.repeat(64) } })).status, 401);
    assert.equal((await fetch(`${url}/conversation/attachments/${randomUUID()}`, { headers: header })).status, 404);
    const note = await db.conversationMessage.findFirstOrThrow({ where: { conversationId: ticket.id, type: 'INTERNAL_NOTE' } });
    const noteFile = await db.conversationAttachment.create({ data: { uploaderId: staff.id, messageId: note.id, storageKey: randomUUID(), originalName: 'secret.txt', mimeType: 'text/plain', size: 1 } });
    assert.equal((await fetch(`${url}/conversation/attachments/${noteFile.id}`, { headers: header })).status, 404);
    assert.equal((await fetch(`${url}/conversation?before=${note.id}`, { headers: header })).status, 400);
    const existing = await db.conversationMessage.findFirstOrThrow({ where: { conversationId: ticket.id, body: 'Initial request' } });
    await db.conversationMessage.createMany({ data: Array.from({ length: 120 }, (_, n) => ({ conversationId: ticket.id, authorId: customer.id, body: `Burst ${n}`, createdAt: new Date(Date.now() + n * 10) })) });
    const after = await (await fetch(`${url}/conversation?after=${existing.id}`, { headers: header })).json();
    assert.equal(after.data.messages.length, 50); assert(after.data.hasMore);
    const next = await (await fetch(`${url}/conversation?after=${after.data.messages.at(-1).id}`, { headers: header })).json();
    assert.equal(next.data.messages.length, 50); assert.notEqual(next.data.messages[0].id, after.data.messages[0].id);
    const inbound = await persistInboundEmail({ mailbox: `form-test-${suffix}`, uid: 1, messageId: `<${suffix}@example.invalid>`, from: { address: email }, subject: `Re: #TK-${ticket.number}`, body: 'Email customer reply', departmentId: department.id });
    assert.equal(inbound, ticket.id);
    assert.equal((await db.conversation.findUniqueOrThrow({ where: { id: ticket.id } })).channel, 'FORM');
    const other = await db.conversation.create({ data: { subject: 'Other', searchSubject: 'other', channel: 'FORM', customerId: customer.id, departmentId: department.id } }); ids.push(other.id);
    const otherMessage = await db.conversationMessage.create({ data: { conversationId: other.id, authorId: customer.id, body: 'OTHER TICKET' } });
    assert.equal((await fetch(`${url}/conversation?before=${otherMessage.id}`, { headers: header })).status, 400);
    const newRequest = new FormData(); newRequest.set('name', 'New Person'); newRequest.set('email', `new-${email}`); newRequest.set('subject', 'Vega'); newRequest.set('message', 'New contact'); newRequest.set('departmentId', department.id);
    newRequest.set('phone', '0530 411 21 50'); newRequest.set('company', 'Example company');
    newRequest.set('turnstileToken', 'form-test-token'); newRequest.set('cf-turnstile-response', 'form-test-token');
    const created = await fetch(`${url}/requests`, { method: 'POST', body: newRequest }); assert.equal(created.status, 201, JSON.stringify(await created.clone().json()));
    const fresh = (await created.json()).data;
    const freshTicket = await db.conversation.findUniqueOrThrow({ where: { number: fresh.number } }); ids.push(freshTicket.id); extraUsers.push(freshTicket.customerId);
    assert.notEqual(freshTicket.customerId, customer.id);
    assert.equal(freshTicket.departmentId, destination.id);
    assert.equal((await db.user.findUniqueOrThrow({ where: { id: freshTicket.customerId } })).phone, '5304112150');
    // File count is unrestricted, including requests larger than the old 10-file cap.
    newRequest.set('email', `files-${email}`);
    for (let n = 0; n < 12; n++) newRequest.append('files', new Blob([`File ${n}`], { type: 'text/plain' }), `form-${n}.txt`);
    const withFiles = await fetch(`${url}/requests`, { method: 'POST', body: newRequest });
    assert.equal(withFiles.status, 201, JSON.stringify(await withFiles.clone().json()));
    const fileTicket = await db.conversation.findUniqueOrThrow({ where: { number: (await withFiles.json()).data.number } }); ids.push(fileTicket.id); extraUsers.push(fileTicket.customerId);
    assert.equal(await db.conversationAttachment.count({ where: { message: { conversationId: fileTicket.id } } }), 12);
    newRequest.delete('files'); newRequest.set('extra', 'unexpected tenth field');
    const extraField = await fetch(`${url}/requests`, { method: 'POST', body: newRequest });
    assert.equal(extraField.status, 400); assert.match((await extraField.json()).error.message, /alan/);
    newRequest.delete('extra'); newRequest.append('files', new Blob([new Uint8Array(30 * 1024 * 1024 + 1)], { type: 'text/plain' }), 'too-big.txt');
    const tooBig = await fetch(`${url}/requests`, { method: 'POST', body: newRequest });
    const tooBigBody = await tooBig.json();
    assert.equal(tooBig.status, 400); assert.match(tooBigBody.error.message, /30 MB/);
    newRequest.delete('files');
    newRequest.append('files', new Blob([Buffer.alloc(16 * 1024 * 1024, 'a')], { type: 'text/plain' }), 'first.txt');
    newRequest.append('files', new Blob([Buffer.alloc(15 * 1024 * 1024, 'a')], { type: 'text/plain' }), 'second.txt');
    const aggregate = await fetch(`${url}/requests`, { method: 'POST', body: newRequest });
    assert.equal(aggregate.status, 400); assert.match((await aggregate.json()).error.message, /toplam.*30 MB/);
    newRequest.delete('files'); newRequest.set('email', `boundary-${email}`);
    newRequest.append('files', new Blob([Buffer.alloc(30 * 1024 * 1024, 'a')], { type: 'text/plain' }), 'thirty-mb.txt');
    const boundary = await fetch(`${url}/requests`, { method: 'POST', body: newRequest });
    assert.equal(boundary.status, 201, JSON.stringify(await boundary.clone().json()));
    const boundaryTicket = await db.conversation.findUniqueOrThrow({ where: { number: (await boundary.json()).data.number } }); ids.push(boundaryTicket.id); extraUsers.push(boundaryTicket.customerId);
    assert.equal((await db.conversationAttachment.findFirstOrThrow({ where: { message: { conversationId: boundaryTicket.id } } })).size, 30 * 1024 * 1024);
    await db.formAccess.updateMany({ where: { tokenHash: formTokenHash(link) }, data: { expiresAt: new Date(0) } });
    assert.equal((await fetch(`${url}/conversation`, { headers: header })).status, 401);
    const freshLink = await db.$transaction(tx => issueFormLink(tx, ticket.id, email));
    assert.equal((await authorizeForm(new URL(freshLink).hash.slice(1))).id, ticket.id);
    // A ticket number and known email never grant access before email-code verification.
    const sendCode = await fetch(`${url}/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ number: ticket.number, email }) });
    assert.equal(sendCode.status, 200);
    const login = (await sendCode.json()).data;
    assert(login.challengeId); assert.equal(login.token, undefined);
    const getCode = async (id: string) => {
      const job = await db.outboundMessage.findUniqueOrThrow({ where: { dedupeKey: `${id}:FORM_LOGIN` } });
      return (job.payload as { text: string }).text.match(/: (\d{6})/)![1];
    };
    const loginCode = await getCode(login.challengeId);
    const wrong = await fetch(`${url}/login/verify`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ challengeId: login.challengeId, code: '000000' }) });
    assert.equal(wrong.status, 400);
    assert.equal((await db.formLoginChallenge.findUniqueOrThrow({ where: { id: login.challengeId } })).attempts, 1);
    const verified = await fetch(`${url}/login/verify`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ challengeId: login.challengeId, code: loginCode }) });
    assert.equal(verified.status, 200);
    const accessToken = (await verified.json()).data.token;
    assert.equal((await authorizeForm(accessToken)).id, ticket.id);
    assert.equal(await db.session.count({ where: { userId: customer.id } }), 0);
    await assert.rejects(verifyFormLogin(login.challengeId, loginCode));
    const jobsBeforeUnknown = await db.outboundMessage.count({ where: { conversationId: ticket.id } });
    const unknown = await fetch(`${url}/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ number: ticket.number, email: 'stranger@example.invalid' }) });
    const unknownLogin = (await unknown.json()).data;
    assert.equal(unknown.status, 200); assert.deepEqual(Object.keys(unknownLogin).sort(), Object.keys(login).sort());
    await assert.rejects(verifyFormLogin(unknownLogin.challengeId, '123456'));
    assert.equal(await db.outboundMessage.count({ where: { conversationId: ticket.id } }), jobsBeforeUnknown);
    const superseded = await requestFormLogin(email, ticket.number), supersededCode = await getCode(superseded.challengeId);
    const current = await requestFormLogin(email, ticket.number), currentCode = await getCode(current.challengeId);
    await assert.rejects(verifyFormLogin(superseded.challengeId, supersededCode));
    for (let n = 0; n < 5; n++) await assert.rejects(verifyFormLogin(current.challengeId, '000000'));
    assert.equal((await db.formLoginChallenge.findUniqueOrThrow({ where: { id: current.challengeId } })).attempts, 5);
    await assert.rejects(verifyFormLogin(current.challengeId, currentCode));
    const expired = await requestFormLogin(email, ticket.number), expiredCode = await getCode(expired.challengeId);
    await db.formLoginChallenge.update({ where: { id: expired.challengeId }, data: { expiresAt: new Date(0) } });
    await assert.rejects(verifyFormLogin(expired.challengeId, expiredCode));
    const once = await requestFormLogin(email, ticket.number), onceCode = await getCode(once.challengeId);
    const races = await Promise.allSettled([verifyFormLogin(once.challengeId, onceCode), verifyFormLogin(once.challengeId, onceCode)]);
    assert.equal(races.filter(item => item.status === 'fulfilled').length, 1);
    const overLimit = await requestFormLogin(email, ticket.number);
    assert.equal(await db.outboundMessage.count({ where: { dedupeKey: `${overLimit.challengeId}:FORM_LOGIN` } }), 0);
    await assert.rejects(verifyFormLogin(overLimit.challengeId, '123456'));
    await db.conversation.update({ where: { id: ticket.id }, data: { deletedAt: new Date() } });
    await assert.rejects(authorizeForm(new URL(freshLink).hash.slice(1)));
  } finally {
    env.TURNSTILE_ENABLED = enabled;
    await new Promise<void>(resolve => server.close(() => resolve()));
    if (originalSettings) await db.formSettings.update({ where: { id: 'default' }, data: originalSettings }); else await db.formSettings.deleteMany({ where: { id: 'default' } });
    await db.notification.deleteMany({ where: { OR: [{ conversationId: { in: ids } }, { userId: { in: [customer.id, staff.id, ...extraUsers] } }] } });
    await db.activityLog.deleteMany({ where: { OR: [{ entityId: { in: ids } }, { userId: { in: [customer.id, staff.id, ...extraUsers] } }] } });
    await discardStoredUploads(await db.conversationAttachment.findMany({ where: { message: { conversationId: { in: ids } } } }));
    await db.conversationMessage.deleteMany({ where: { conversationId: { in: ids } } });
    await db.conversation.deleteMany({ where: { id: { in: ids } } });
    await db.user.deleteMany({ where: { id: { in: [customer.id, staff.id, ...extraUsers] } } });
    await db.department.deleteMany({ where: { id: { in: [department.id, destination.id, inactive.id] } } });
    db.$transaction = originalTx; db.integrationSettings.findUnique = originalSmtp; await db.$disconnect();
  }
});
