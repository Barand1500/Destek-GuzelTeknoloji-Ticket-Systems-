import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Source: https://github.com/berkaybucan/turkey-bin-list (MIT License).
// Usage: node scripts/generate-bin-data.mjs [path-to-turkey_bin_list.json]
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2] ?? path.join(root, '..', 'tmp', 'turkey_bin_list.json');
const output = path.join(root, 'src', 'services', 'turkey-bin-data.ts');

let rows;
try {
  rows = JSON.parse(await readFile(source, 'utf8'));
} catch {
  const response = await fetch('https://raw.githubusercontent.com/berkaybucan/turkey-bin-list/main/turkey_bin_list.json');
  if (!response.ok) throw new Error(`BIN list could not be downloaded: ${response.status}`);
  rows = await response.json();
}
const records = new Map();

for (const row of Array.isArray(rows) ? rows : []) {
  const bin = String(row?.BIN ?? '').trim();
  const issuer = String(row?.Issuer ?? '').trim();
  if (!/^\d{6}$/.test(bin) || !issuer) continue;
  records.set(bin, {
    issuer,
    network: String(row?.Network ?? '').trim().toUpperCase(),
    type: String(row?.Type ?? '').trim().toUpperCase(),
    category: String(row?.Category ?? '').trim().toUpperCase(),
  });
}

const quote = (value) => JSON.stringify(value);
const entries = [...records.entries()].sort(([left], [right]) => left.localeCompare(right));
const body = entries
  .map(([bin, record]) =>
    `  ${quote(bin)}: { issuer: ${quote(record.issuer)}, network: ${quote(record.network)}, type: ${quote(record.type)}, category: ${quote(record.category)} },`,
  )
  .join('\n');

const text = `// Generated by scripts/generate-bin-data.mjs. Do not edit by hand.
// Source: https://github.com/berkaybucan/turkey-bin-list (MIT License), retrieved 2026-11-17.
// See THIRD_PARTY_NOTICES.md. Turkish card BIN prefixes (first 6 digits) and issuer metadata.

export type TurkeyBinRecord = {
  issuer: string;
  network: string;
  type: string;
  category: string;
};

export const TURKEY_BIN_RECORDS: Record<string, TurkeyBinRecord> = {
${body}
};
`;

await writeFile(output, text, 'utf8');
console.log(`Wrote ${entries.length} BIN records to ${path.relative(root, output)}`);
