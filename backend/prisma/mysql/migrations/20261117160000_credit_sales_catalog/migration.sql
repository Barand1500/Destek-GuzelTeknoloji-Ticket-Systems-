CREATE TABLE CreditSalesSettings (
 id VARCHAR(32) NOT NULL DEFAULT 'default', enabled BOOLEAN NOT NULL DEFAULT false,
 unitPrice DECIMAL(10,2) NOT NULL DEFAULT 1, minCredits INTEGER NOT NULL DEFAULT 1,
 maxCredits INTEGER NOT NULL DEFAULT 10000, validityDays INTEGER NOT NULL DEFAULT 365,
 updatedAt DATETIME(3) NOT NULL, PRIMARY KEY (id)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE CreditSalesPlan (
 id VARCHAR(191) NOT NULL, name VARCHAR(100) NOT NULL, description TEXT NOT NULL,
 periodMonths INTEGER NOT NULL, price DECIMAL(10,2) NOT NULL, credits INTEGER NOT NULL,
 active BOOLEAN NOT NULL DEFAULT false, createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updatedAt DATETIME(3) NOT NULL, PRIMARY KEY (id), INDEX CreditSalesPlan_active_createdAt_idx (active, createdAt)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
