CREATE TABLE `OutboundMessage` (
  `id` VARCHAR(191) NOT NULL,
  `dedupeKey` VARCHAR(191) NULL,
  `channel` VARCHAR(16) NOT NULL,
  `payload` JSON NOT NULL,
  `conversationId` VARCHAR(191) NULL,
  `userId` VARCHAR(191) NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  `sequence` INTEGER NOT NULL DEFAULT 0,
  `attempts` INTEGER NOT NULL DEFAULT 0,
  `availableAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `leaseToken` VARCHAR(36) NULL,
  `leaseUntil` DATETIME(3) NULL,
  `lastError` TEXT NULL,
  `providerMessageId` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `OutboundMessage_dedupeKey_key` (`dedupeKey`),
  INDEX `OutboundMessage_status_availableAt_idx` (`status`, `availableAt`),
  INDEX `OutboundMessage_conversationId_channel_status_idx` (`conversationId`, `channel`, `status`),
  INDEX `OutboundMessage_userId_idx` (`userId`),
  CONSTRAINT `OutboundMessage_conversationId_fkey` FOREIGN KEY (`conversationId`) REFERENCES `Conversation` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `OutboundMessage_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
